function designIdFor(name) {
  return String(name ?? "").toLowerCase().replace(/[^a-z0-9]+/g, "-");
}

export function designSlugFor(item) {
  if (!item) return null;
  const candidates = [item.slug, item.id, designIdFor(item.name)].filter(Boolean);
  return candidates.find((candidate) => doorDesigns.some((design) => design.slug === candidate)) ?? null;
}

function productItem(name, img, shortDesc, description, altText) {
  const id = designIdFor(name);
  return {
    id,
    slug: doorDesigns.some((design) => design.slug === id) ? id : undefined,
    name,
    shortDesc,
    img,
    altText,
    params: {
      style: "Minimalist Modern",
      material: "Steel + Aluminum Honeycomb",
      configuration: "Single or double",
      smartLock: "Optional",
      size: "Up to 1980x2500mm"
    },
    description
  };
}
